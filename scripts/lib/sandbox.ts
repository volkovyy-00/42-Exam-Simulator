// Runs a reference solution inside the grader image with the DESIGN.md §6.3 `docker run` flags
// and the graded compile flags. The grader's runner.sh belongs to WP1, so the pipeline ships
// its own small in-container script (generated per job, copied into the read-only /in) that
// mirrors runner.sh's stages: compile A, compile B + `nm -u`, link, then each test with
// `setsid timeout -s KILL`, `ulimit -t/-s`, argv without a shell, stdin or /dev/null.
import { spawnSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { chmodSync, copyFileSync, mkdtempSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import type { Exercise } from '@ceg/contract';
import { GRADER_IMAGE_DIR } from './content.ts';

export const DEFAULT_IMAGE = 'grader:pinned';
export const GRADED_CFLAGS = ['-Wall', '-Wextra', '-Werror'];
const STDERR_CAP = 16384;
const TEST_CPU_S = 1;
const COMPILE_TIMEOUT_S = 10;

export interface RefTestRun {
  id: string;
  stdout: Buffer;
  exit: number;
  signal: number | null;
  timed_out: boolean;
  truncated: boolean;
}

export interface RefRun {
  copy_ok: boolean;
  compile_ok: boolean;
  compile_stderr: string;
  /** `nm -u` of the reference object built with -fno-builtin, one leading `_` stripped. */
  nm_symbols: string[];
  nm_ok: boolean;
  link_ok: boolean;
  link_stderr: string;
  tests: RefTestRun[];
  /** Docker-level failure (image missing, daemon down, outer timeout). */
  error: string | null;
}

/** POSIX sh single-quoting: safe for any bytes, including newlines. */
export function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** The `docker run` argv of DESIGN.md §6.3 for a job dir mounted at /in. */
export function dockerRunArgs(name: string, jobIn: string, image: string, cmd: string[]): string[] {
  return [
    'run', '--rm', '--name', name, '--network', 'none', '--cap-drop', 'ALL',
    '--security-opt', 'no-new-privileges', '--user', '65534:65534', '--read-only',
    '--tmpfs', '/work:rw,exec,nosuid,nodev,size=16m,uid=65534,gid=65534',
    '--tmpfs', '/tmp:rw,noexec,nosuid,nodev,size=8m',
    '-v', `${jobIn}:/in:ro`, '--pids-limit', '64', '--memory', '256m', '--memory-swap', '256m',
    '--cpus', '1', '--ulimit', 'nofile=64:64', '--ulimit', 'fsize=8388608:8388608',
    '--ulimit', 'core=0:0', '--ulimit', 'cpu=20:20', '--log-opt', 'max-size=1m',
    '-w', '/work', image, ...cmd,
  ];
}

export function docker(args: string[], opts: { timeoutMs?: number; input?: string } = {}) {
  return spawnSync('docker', args, {
    encoding: 'buffer', timeout: opts.timeoutMs ?? 0, maxBuffer: 256 * 1024 * 1024, input: opts.input,
  });
}

export function dockerAvailable(): boolean {
  const r = docker(['info', '--format', '{{.ServerVersion}}'], { timeoutMs: 20000 });
  return r.status === 0;
}

export function imageExists(image: string): boolean {
  return docker(['image', 'inspect', image], { timeoutMs: 20000 }).status === 0;
}

/**
 * Makes sure the grader image exists. The default grader:pinned is built from grader/image
 * (read-only use of that folder) when missing; any other image must already exist.
 */
export function ensureImage(image: string, log: (s: string) => void = console.log): void {
  if (!dockerAvailable()) throw new Error('docker is not available (is the daemon running?)');
  if (imageExists(image)) return;
  if (image !== DEFAULT_IMAGE) throw new Error(`image ${image} not found`);
  log(`${image} not found: building it from ${GRADER_IMAGE_DIR}`);
  const r = spawnSync('docker', ['build', '-t', image, GRADER_IMAGE_DIR], { stdio: 'inherit', timeout: 30 * 60 * 1000 });
  if (r.status !== 0) {
    throw new Error(`could not build ${image} from ${GRADER_IMAGE_DIR} (docker build exited ${r.status}). `
      + 'Build it on a host with Debian mirror access, or pass --image <tag> to use another image.');
  }
}

/** Generates the in-container script for one exercise. Exported for tests. */
export function refScript(ex: Exercise, studentFile: string): string {
  const flags = [...GRADED_CFLAGS, ...ex.harness.cflags_extra].map(shQuote).join(' ');
  const timeoutS = Math.min(10, Math.max(2, Math.ceil(ex.limits.timeout_ms / 1000)));
  const cap = ex.limits.max_output_bytes + 1;
  const sf = shQuote(studentFile);
  const L: string[] = [
    '#!/bin/sh',
    '# Generated by scripts/lib/sandbox.ts. Prints "CEG ..." lines; never sees expected output.',
    'set -u',
    'cp -r /in/. /work/ || { echo "CEG COPY 1"; exit 0; }',
    'cd /work || { echo "CEG COPY 1"; exit 0; }',
    'echo "CEG COPY 0"',
    `if timeout -s KILL ${COMPILE_TIMEOUT_S} cc ${flags} -c ${sf} -o student.o 2>ca.err; then echo "CEG COMPILE 0 $(head -c ${STDERR_CAP} ca.err | base64 -w0)"; else echo "CEG COMPILE 1 $(head -c ${STDERR_CAP} ca.err | base64 -w0)"; exit 0; fi`,
    `if timeout -s KILL ${COMPILE_TIMEOUT_S} cc ${flags} -fno-builtin -c ${sf} -o student_nm.o 2>cb.err; then echo "CEG NM $(nm -u student_nm.o | awk '{print $NF}' | tr '\\n' ' ')"; else echo "CEG NMFAIL $(head -c ${STDERR_CAP} cb.err | base64 -w0)"; exit 0; fi`,
  ];
  if (ex.kind === 'function') {
    L.push(`if timeout -s KILL ${COMPILE_TIMEOUT_S} cc ${flags} -c main.c -o main.o 2>ln.err && cc student.o main.o -o a.out 2>>ln.err; then echo "CEG LINK 0"; else echo "CEG LINK 1 $(head -c ${STDERR_CAP} ln.err | base64 -w0)"; exit 0; fi`);
  } else {
    L.push(`if cc student.o -o a.out 2>ln.err; then echo "CEG LINK 0"; else echo "CEG LINK 1 $(head -c ${STDERR_CAP} ln.err | base64 -w0)"; exit 0; fi`);
  }
  L.push('mkdir -p out');
  for (const t of ex.tests) {
    const stdin = t.stdin === null ? '/dev/null' : `cases/${t.id}.in`;
    L.push(
      `( ulimit -t ${TEST_CPU_S} -s 8192; exec setsid timeout -s KILL ${timeoutS} sh cases/${t.id}.sh ) <${stdin} >out/${t.id} 2>/dev/null; rc=$?`,
      `echo "CEG TEST ${t.id} $rc $(wc -c <out/${t.id}) $(head -c ${cap} out/${t.id} | base64 -w0)"`,
    );
  }
  L.push('echo "CEG END"');
  return L.join('\n') + '\n';
}

/** Parses the script's stdout. Exported for tests. */
export function parseRefOutput(stdout: string, maxOutput: number): RefRun {
  const run: RefRun = {
    copy_ok: false, compile_ok: false, compile_stderr: '', nm_symbols: [], nm_ok: false,
    link_ok: false, link_stderr: '', tests: [], error: null,
  };
  const b64 = (s: string | undefined) => Buffer.from(s ?? '', 'base64').toString('utf8');
  let ended = false;
  for (const line of stdout.split('\n')) {
    if (!line.startsWith('CEG ')) continue;
    const p = line.split(' ');
    switch (p[1]) {
      case 'COPY': run.copy_ok = p[2] === '0'; break;
      case 'COMPILE': run.compile_ok = p[2] === '0'; run.compile_stderr = b64(p[3]); break;
      case 'NM':
        run.nm_ok = true;
        run.nm_symbols = [...new Set(p.slice(2).filter((s) => s.length > 0).map((s) => s.replace(/^_/, '')))].sort();
        break;
      case 'NMFAIL': run.compile_stderr = b64(p[2]); break;
      case 'LINK': run.link_ok = p[2] === '0'; run.link_stderr = b64(p[3]); break;
      case 'TEST': {
        const rc = Number(p[3]);
        const size = Number(p[4]);
        let out = Buffer.from(p[5] ?? '', 'base64');
        const truncated = size > maxOutput;
        if (out.length > maxOutput) out = out.subarray(0, maxOutput + 1);
        const timed_out = rc === 124;
        const signal = !timed_out && rc > 128 ? rc - 128 : null;
        run.tests.push({ id: p[2]!, stdout: out, exit: signal === null && !timed_out ? rc : -1, signal, timed_out, truncated });
        break;
      }
      case 'END': ended = true; break;
    }
  }
  if (!ended && run.link_ok) run.error = 'sandbox output ended early';
  return run;
}

/** Compiles, links and runs one exercise's reference in the grader image. */
export function runReference(ex: Exercise, root: string, image: string): RefRun {
  const job = mkdtempSync(join(tmpdir(), 'ceg-ref-'));
  const jobIn = join(job, 'in');
  mkdirSync(join(jobIn, 'cases'), { recursive: true });
  const studentFile = ex.expected_files[0] ?? `${ex.id}.c`;
  try {
    copyFileSync(join(root, ex.reference_path), join(jobIn, studentFile));
    if (ex.harness.main) copyFileSync(join(root, ex.harness.main), join(jobIn, 'main.c'));
    for (const inc of ex.harness.includes) copyFileSync(join(root, inc), join(jobIn, basename(inc)));
    for (const t of ex.tests) {
      writeFileSync(join(jobIn, 'cases', `${t.id}.sh`), `exec ./a.out ${t.argv.map(shQuote).join(' ')}\n`);
      if (t.stdin !== null) writeFileSync(join(jobIn, 'cases', `${t.id}.in`), t.stdin);
    }
    writeFileSync(join(jobIn, 'ref_run.sh'), refScript(ex, studentFile));
    // The sandbox runs as 65534: everything must be world-readable.
    spawnSync('chmod', ['-R', 'a+rX', job]);
    chmodSync(job, 0o755);
    const name = `ceg-content-${randomUUID()}`;
    const deadline = (COMPILE_TIMEOUT_S * 3 + ex.tests.length * 12 + 30) * 1000;
    const r = docker(dockerRunArgs(name, jobIn, image, ['sh', '/in/ref_run.sh']), { timeoutMs: deadline });
    const out = parseRefOutput(r.stdout?.toString('utf8') ?? '', ex.limits.max_output_bytes);
    if (r.error || r.status !== 0) {
      docker(['rm', '-f', name], { timeoutMs: 30000 });
      out.error = r.error ? `docker run failed: ${r.error.message}`
        : `docker run exited ${r.status}: ${r.stderr?.toString('utf8').trim().slice(0, 500)}`;
    } else if (!out.copy_ok) {
      out.error = 'copy /in → /work failed in the sandbox';
    }
    return out;
  } finally {
    rmSync(job, { recursive: true, force: true });
  }
}
